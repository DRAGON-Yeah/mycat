import { dumpTableSql, listTables } from "../connections/sessionApi";
import type { ConnectionDto } from "../connections/types";
import { engineKey, quoteIdent } from "../nav-tree/sqlIdent";
import type { SqlFileLogLevel } from "./runSqlFile";

export type DumpSqlFileOptions = {
  conn: ConnectionDto;
  database: string;
  includeData: boolean;
  cancel: { cancelled: boolean };
  onLog: (level: SqlFileLogLevel, text: string) => void;
  onProgress: (done: number, total: number, failed: number) => void;
};

export type DumpSqlFileResult = {
  sql: string;
  tables: number;
  failed: number;
  cancelled: boolean;
  elapsedMs: number;
};

function escapeIdent(name: string) {
  return name.replace(/`/g, "``");
}

export function defaultDumpFileName(database: string, includeData: boolean) {
  return `${database || "dump"}${includeData ? "" : "-structure"}.sql`;
}

/** 逐表生成转储 SQL，通过回调上报进度与日志。 */
export async function buildDumpSql(
  args: DumpSqlFileOptions,
): Promise<DumpSqlFileResult> {
  const started = Date.now();
  const engine = String(args.conn.engine);
  const tables = await listTables(args.conn.id, args.database);
  const baseTables = tables.filter((t) => t.kind !== "view");
  const total = baseTables.length;

  args.onProgress(0, total, 0);
  args.onLog(
    "info",
    `数据库 ${args.database} · ${engine} · ${total} 张表 · ${
      args.includeData ? "结构和数据" : "仅结构"
    }`,
  );

  if (total === 0) {
    args.onLog("warn", "没有可转储的表");
    return {
      sql: "",
      tables: 0,
      failed: 0,
      cancelled: false,
      elapsedMs: Date.now() - started,
    };
  }

  const parts: string[] =
    engineKey(engine) === "mysql"
      ? [
          `-- Dump of database \`${args.database}\``,
          `-- Generated by Mycat`,
          `-- Date: ${new Date().toLocaleString()}`,
          `CREATE DATABASE IF NOT EXISTS \`${escapeIdent(args.database)}\`;`,
          `USE \`${escapeIdent(args.database)}\`;`,
          "",
        ]
      : [
          `-- Dump of database ${quoteIdent(engine, args.database)}`,
          `-- Generated by Mycat`,
          `-- Date: ${new Date().toLocaleString()}`,
          "",
        ];

  let done = 0;
  let failed = 0;
  let cancelled = false;

  for (let i = 0; i < baseTables.length; i += 1) {
    if (args.cancel.cancelled) {
      cancelled = true;
      args.onLog("warn", "已停止转储（剩余表未导出）");
      break;
    }
    const table = baseTables[i]!;
    args.onLog("info", `[${i + 1}/${total}] ${table.name}`);
    try {
      const sql = await dumpTableSql({
        connectionId: args.conn.id,
        table: table.name,
        includeData: args.includeData,
        engine,
        database: args.database,
      });
      parts.push(sql, "");
      done += 1;
      args.onLog(
        "ok",
        `[${i + 1}/${total}] ${table.name} · ${(sql.length / 1024).toFixed(1)} KB`,
      );
    } catch (err) {
      failed += 1;
      const message = err instanceof Error ? err.message : String(err);
      args.onLog("error", `[${i + 1}/${total}] ${table.name} 失败：${message}`);
    }
    args.onProgress(done + failed, total, failed);
  }

  return {
    sql: parts.join("\n"),
    tables: done,
    failed,
    cancelled,
    elapsedMs: Date.now() - started,
  };
}
