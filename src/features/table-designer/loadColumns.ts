function colMap(columns: string[]): Record<string, number> {
  const m: Record<string, number> = {};
  columns.forEach((c, i) => {
    m[c.toLowerCase()] = i;
  });
  return m;
}

function cell(row: unknown[], idx: number | undefined): string {
  if (idx == null || idx < 0) return "";
  const v = row[idx];
  if (v == null) return "";
  return String(v);
}

function esc(value: string): string {
  return value.replace(/'/g, "''");
}

/** `n.nspname = ...` predicate for the schema carried by a qualified name. */
function pgSchemaPredicate(table: string, alias = "n"): string {
  const [schema] = splitQualified(table);
  return schema
    ? `${alias}.nspname = '${esc(schema)}'`
    : `${alias}.nspname = current_schema()`;
}

function pgTableName(table: string): string {
  return esc(splitQualified(table)[1]);
}

const PG_TYPE_ALIASES: Record<string, string> = {
  "character varying": "varchar",
  character: "char",
  "timestamp without time zone": "timestamp",
  "timestamp with time zone": "timestamptz",
  "time without time zone": "time",
  "time with time zone": "timetz",
  "bit varying": "varbit",
};

/** `format_type()` output → designer type/length/decimals. */
export function parsePgType(raw: string): {
  typeName: string;
  length: string;
  decimals: string;
} {
  const s = raw.trim();
  const m = s.match(/^([^(]+?)\s*\((\d+)(?:\s*,\s*(\d+))?\)$/);
  const base = (m ? m[1]! : s).trim().toLowerCase();
  return {
    typeName: PG_TYPE_ALIASES[base] ?? base,
    length: m?.[2] ?? "",
    decimals: m?.[3] ?? "",
  };
}

export async function loadDesignerColumns(args: {
  connectionId: string;
  engine: string;
  database: string;
  table: string;
}): Promise<DesignerColumn[]> {
  const { connectionId, engine, database, table } = args;
  await openConnection(connectionId);
  const e = engineKey(engine);

  if (e === "sqlite") {
    const out = await executeSql(
      connectionId,
      `PRAGMA table_info(${quoteTable(engine, null, table)})`,
      database,
    );
    return out.rows.map((row) => {
      const name = String(row[1] ?? "");
      const parsed = parseRawType(String(row[2] ?? "TEXT") || "TEXT");
      const notnull = Number(row[3] ?? 0) === 1;
      const dflt = row[4] == null ? null : String(row[4]);
      const pk = Number(row[5] ?? 0) > 0;
      return newColumn({
        name,
        typeName: parsed.typeName,
        length: parsed.length,
        decimals: parsed.decimals,
        notNull: notnull,
        isPk: pk,
        defaultValue: dflt,
        originalName: name,
      });
    });
  }

  if (isPostgres(engine)) {
    const sql = `SELECT a.attname AS column_name,
       pg_catalog.format_type(a.atttypid, a.atttypmod) AS data_type,
       a.attnotnull AS not_null,
       COALESCE(pg_catalog.pg_get_expr(d.adbin, d.adrelid), '') AS column_default,
       COALESCE(pg_catalog.col_description(c.oid, a.attnum), '') AS comment,
       a.attidentity AS identity,
       a.attgenerated AS generated,
       COALESCE((SELECT true FROM pg_catalog.pg_constraint con
                  WHERE con.conrelid = c.oid AND con.contype = 'p'
                    AND a.attnum = ANY(con.conkey)), false) AS is_pk
FROM pg_catalog.pg_attribute a
JOIN pg_catalog.pg_class c ON c.oid = a.attrelid
JOIN pg_catalog.pg_namespace n ON n.oid = c.relnamespace
LEFT JOIN pg_catalog.pg_attrdef d ON d.adrelid = c.oid AND d.adnum = a.attnum
WHERE c.relname = '${pgTableName(table)}'
  AND ${pgSchemaPredicate(table)}
  AND a.attnum > 0 AND NOT a.attisdropped
ORDER BY a.attnum`;
    const out = await executeSql(connectionId, sql, database);
    const m = colMap(out.columns);
    return out.rows.map((row) => {
      const name = cell(row, m.column_name);
      const parsed = parsePgType(cell(row, m.data_type) || "text");
      const identity = cell(row, m.identity);
      const generated = cell(row, m.generated);
      const extra = identity
        ? identity === "a"
          ? "GENERATED ALWAYS AS IDENTITY"
          : "GENERATED BY DEFAULT AS IDENTITY"
        : generated
          ? "GENERATED ALWAYS AS (...) STORED"
          : "";
      return newColumn({
        name,
        typeName: parsed.typeName,
        length: parsed.length,
        decimals: parsed.decimals,
        notNull: cell(row, m.not_null).toLowerCase() === "t",
        virtual: generated === "s",
        isPk: cell(row, m.is_pk).toLowerCase() === "t",
        defaultValue: cell(row, m.column_default) || null,
        comment: cell(row, m.comment),
        originalName: name,
        extra,
      });
    });
  }

  const qt = quoteTable(engine, database, table);
  const out = await executeSql(connectionId, `SHOW FULL COLUMNS FROM ${qt}`, database);
  const m = colMap(out.columns);
  return out.rows.map((row) => {
    const name = cell(row, m.field);
    const parsed = parseRawType(cell(row, m.type) || "varchar(255)");
    const nullable = cell(row, m.null).toUpperCase() === "YES";
    const key = cell(row, m.key).toUpperCase();
    const dfltRaw = m.default != null ? row[m.default] : null;
    const dflt = dfltRaw == null ? null : String(dfltRaw);
    const extra = cell(row, m.extra);
    const virtual = /virtual|stored generated/i.test(extra);
    return newColumn({
      name,
      typeName: parsed.typeName,
      length: parsed.length,
      decimals: parsed.decimals,
      notNull: !nullable,
      virtual,
      isPk: key === "PRI",
      defaultValue: dflt,
      comment: cell(row, m.comment),
      originalName: name,
      extra,
    });
  });
}

export async function loadMysqlCharsets(args: {
  connectionId: string;
}): Promise<{ charsets: string[]; collationsByCharset: Record<string, string[]> }> {
  await openConnection(args.connectionId);
  const charsets: string[] = [];
  const collationsByCharset: Record<string, string[]> = {};
  try {
    const cs = await executeSql(args.connectionId, "SHOW CHARACTER SET");
    const m = colMap(cs.columns);
    for (const row of cs.rows) {
      const name = cell(row, m.charset ?? m.Charset);
      if (name) charsets.push(name);
    }
  } catch {
    /* fallback elsewhere */
  }
  try {
    const cl = await executeSql(args.connectionId, "SHOW COLLATION");
    const m = colMap(cl.columns);
    for (const row of cl.rows) {
      const coll = cell(row, m.collation ?? m.Collation);
      const cs = cell(row, m.charset ?? m.Charset);
      if (!coll || !cs) continue;
      if (!collationsByCharset[cs]) collationsByCharset[cs] = [];
      collationsByCharset[cs]!.push(coll);
    }
  } catch {
    /* fallback elsewhere */
  }
  return { charsets, collationsByCharset };
}

export async function loadTableOptions(args: {
  connectionId: string;
  engine: string;
  database: string;
  table: string;
}): Promise<{ options: TableOptions; stats: TableInfoStats }> {
  const { connectionId, engine, database, table } = args;
  const emptyStats: TableInfoStats = {
    tableRows: "—",
    dataLength: "—",
    indexLength: "—",
    createTime: "—",
    updateTime: "—",
  };
  const e = engineKey(engine);

  if (isPostgres(engine)) {
    await openConnection(connectionId);
    const sql = `SELECT c.reltuples::bigint AS est_rows,
       pg_catalog.pg_total_relation_size(c.oid) AS total_bytes,
       pg_catalog.pg_relation_size(c.oid) AS table_bytes,
       pg_catalog.pg_indexes_size(c.oid) AS index_bytes,
       COALESCE(pg_catalog.obj_description(c.oid, 'pg_class'), '') AS comment,
       pg_catalog.pg_get_userbyid(c.relowner) AS owner,
       COALESCE(ts.spcname, '') AS tablespace
FROM pg_catalog.pg_class c
JOIN pg_catalog.pg_namespace n ON n.oid = c.relnamespace
LEFT JOIN pg_catalog.pg_tablespace ts ON ts.oid = c.reltablespace
WHERE c.relname = '${pgTableName(table)}'
  AND ${pgSchemaPredicate(table)}`;
    const out = await executeSql(connectionId, sql, database);
    const row = out.rows[0];
    if (!row) return { options: emptyOptions(), stats: emptyStats };
    const rowsEst = Number(row[0] ?? 0);
    const owner = String(row[5] ?? "");
    const tablespace = String(row[6] ?? "");
    return {
      options: {
        engine: owner ? `PostgreSQL · ${owner}` : "PostgreSQL",
        charset: "",
        collation: tablespace,
        rowFormat: "",
        autoIncrement: "",
        comment: String(row[4] ?? ""),
        avgRowLength: "",
      },
      stats: {
        tableRows: `${rowsEst} (Est.)`,
        dataLength: formatBytes(Number(row[1] ?? 0)),
        indexLength: formatBytes(Number(row[3] ?? 0)),
        createTime: "—",
        updateTime: "—",
      },
    };
  }

  if (e === "sqlite") {
    await openConnection(connectionId);
    let rows = "—";
    try {
      const cnt = await executeSql(
        connectionId,
        `SELECT COUNT(*) FROM ${quoteTable(engine, null, table)}`,
        database,
      );
      const n = Number(cnt.rows[0]?.[0] ?? 0);
      rows = Number.isFinite(n) ? String(n) : "—";
    } catch {
      /* ignore */
    }
    let dataLength = "—";
    try {
      const pc = await executeSql(connectionId, "PRAGMA page_count", database);
      const ps = await executeSql(connectionId, "PRAGMA page_size", database);
      const total =
        Number(pc.rows[0]?.[0] ?? 0) * Number(ps.rows[0]?.[0] ?? 0);
      if (total > 0) dataLength = formatBytes(total);
    } catch {
      /* ignore */
    }
    return {
      options: {
        engine: "SQLite",
        charset: "",
        collation: "",
        rowFormat: "",
        autoIncrement: "",
        comment: "",
        avgRowLength: "",
      },
      stats: {
        tableRows: rows,
        dataLength,
        indexLength: "—",
        createTime: "—",
        updateTime: "—",
      },
    };
  }

  if (e !== "mysql") {
    return { options: emptyOptions(), stats: emptyStats };
  }
  await openConnection(connectionId);
  const sql = `SELECT ENGINE, TABLE_COLLATION, ROW_FORMAT, AUTO_INCREMENT, TABLE_COMMENT,
  TABLE_ROWS, DATA_LENGTH, INDEX_LENGTH,
  DATE_FORMAT(CREATE_TIME,'%Y-%m-%d %H:%i:%s'),
  DATE_FORMAT(UPDATE_TIME,'%Y-%m-%d %H:%i:%s'),
  AVG_ROW_LENGTH
FROM information_schema.TABLES
WHERE TABLE_SCHEMA = '${database.replace(/'/g, "''")}'
  AND TABLE_NAME = '${table.replace(/'/g, "''")}'`;
  const out = await executeSql(connectionId, sql, database);
  const row = out.rows[0];
  if (!row) return { options: emptyOptions(), stats: emptyStats };
  const coll = String(row[1] ?? "utf8mb4_unicode_ci");
  const charset = coll.split("_")[0] || "utf8mb4";
  return {
    options: {
      engine: String(row[0] ?? "InnoDB"),
      charset,
      collation: coll,
      rowFormat: String(row[2] ?? "Dynamic"),
      autoIncrement: row[3] == null ? "" : String(row[3]),
      comment: String(row[4] ?? ""),
      avgRowLength: row[10] == null ? "" : String(row[10]),
    },
    stats: {
      tableRows: row[5] == null ? "—" : `${row[5]} (Est.)`,
      dataLength: formatBytes(Number(row[6] ?? 0)),
      indexLength: formatBytes(Number(row[7] ?? 0)),
      createTime: String(row[8] ?? "—"),
      updateTime: String(row[9] ?? "—"),
    },
  };
}

function formatBytes(n: number): string {
  if (!n || Number.isNaN(n)) return "0 B";
  if (n < 1024) return `${n} B`;
  if (n < 1024 * 1024) return `${(n / 1024).toFixed(0)} KB`;
  return `${(n / (1024 * 1024)).toFixed(1)} MB`;
}

export async function loadDesignerIndexes(args: {
  connectionId: string;
  engine: string;
  database: string;
  table: string;
}): Promise<DesignerIndex[]> {
  const { connectionId, engine, database, table } = args;
  await openConnection(connectionId);

  if (isPostgres(engine)) {
    const sql = `SELECT i.relname AS index_name,
       x.indisunique AS is_unique,
       am.amname AS index_type,
       COALESCE((SELECT string_agg(pg_catalog.pg_get_indexdef(x.indexrelid, k, true), ','
                                  ORDER BY k)
                 FROM generate_series(1, x.indnkeyatts) AS k), '') AS columns,
       COALESCE((SELECT true FROM pg_catalog.pg_constraint con
                 WHERE con.conindid = x.indexrelid AND con.contype = 'p'), false) AS is_pk
FROM pg_catalog.pg_index x
JOIN pg_catalog.pg_class i ON i.oid = x.indexrelid
JOIN pg_catalog.pg_class c ON c.oid = x.indrelid
JOIN pg_catalog.pg_namespace n ON n.oid = c.relnamespace
JOIN pg_catalog.pg_am am ON am.oid = i.relam
WHERE c.relname = '${pgTableName(table)}'
  AND ${pgSchemaPredicate(table)}
ORDER BY i.relname`;
    const out = await executeSql(connectionId, sql, database);
    return out.rows.map((row) => {
      const name = String(row[0] ?? "");
      const isPk = String(row[4] ?? "").toLowerCase() === "t";
      return {
        key: `ix-${name}`,
        name,
        columns: String(row[3] ?? ""),
        unique: isPk || String(row[1] ?? "").toLowerCase() === "t",
        indexType: String(row[2] ?? "btree").toUpperCase(),
        originalName: name,
      };
    });
  }

  if (engineKey(engine) === "sqlite") {
    const list = await executeSql(
      connectionId,
      `PRAGMA index_list(${sqliteLiteral(table)})`,
      database,
    );
    const m = colMap(list.columns);
    const out: DesignerIndex[] = [];
    for (const row of list.rows) {
      const name = cell(row, m.name);
      const origin = cell(row, m.origin);
      // Implicit UNIQUE / PRIMARY KEY indexes cannot be edited on their own.
      if (!name || name.startsWith("sqlite_autoindex") || origin === "pk") continue;
      const info = await executeSql(
        connectionId,
        `PRAGMA index_info(${sqliteLiteral(name)})`,
        database,
      );
      const im = colMap(info.columns);
      const cols = info.rows
        .map((r) => cell(r, im.name))
        .filter(Boolean)
        .join(", ");
      if (!cols) continue;
      out.push({
        key: `ix-${name}`,
        name,
        columns: cols,
        unique: cell(row, m.unique) === "1",
        indexType: "BTREE",
        originalName: name,
      });
    }
    return out;
  }

  if (engineKey(engine) !== "mysql") return [];
  const qt = quoteTable(engine, database, table);
  const out = await executeSql(connectionId, `SHOW INDEX FROM ${qt}`, database);
  const m = colMap(out.columns);
  const byName = new Map<string, DesignerIndex>();
  for (const row of out.rows) {
    const name = cell(row, m.key_name);
    if (!name) continue;
    const col = cell(row, m.column_name);
    const unique = Number(cell(row, m.non_unique) || 1) === 0;
    const indexType = cell(row, m.index_type) || "BTREE";
    const prev = byName.get(name);
    if (prev) {
      prev.columns = `${prev.columns}, ${col}`;
    } else {
      byName.set(name, {
        key: `ix-${name}`,
        name,
        columns: col,
        unique: name.toUpperCase() === "PRIMARY" ? true : unique,
        indexType,
        originalName: name,
      });
    }
  }
  return [...byName.values()];
}

const PG_FK_ACTION: Record<string, string> = {
  a: "NO ACTION",
  r: "RESTRICT",
  c: "CASCADE",
  n: "SET NULL",
  d: "SET DEFAULT",
};

export async function loadDesignerForeignKeys(args: {
  connectionId: string;
  engine: string;
  database: string;
  table: string;
}): Promise<DesignerForeignKey[]> {
  const { connectionId, engine, database, table } = args;
  await openConnection(connectionId);

  if (isPostgres(engine)) {
    const sql = `SELECT con.conname AS name,
       COALESCE((SELECT string_agg(a.attname, ',' ORDER BY k.ord)
                 FROM unnest(con.conkey) WITH ORDINALITY AS k(attnum, ord)
                 JOIN pg_catalog.pg_attribute a
                   ON a.attrelid = con.conrelid AND a.attnum = k.attnum), '') AS columns,
       rc.relname AS ref_table,
       rn.nspname AS ref_schema,
       COALESCE((SELECT string_agg(a.attname, ',' ORDER BY k.ord)
                 FROM unnest(con.confkey) WITH ORDINALITY AS k(attnum, ord)
                 JOIN pg_catalog.pg_attribute a
                   ON a.attrelid = con.confrelid AND a.attnum = k.attnum), '') AS ref_columns,
       con.confdeltype AS on_delete,
       con.confupdtype AS on_update
FROM pg_catalog.pg_constraint con
JOIN pg_catalog.pg_class c ON c.oid = con.conrelid
JOIN pg_catalog.pg_namespace n ON n.oid = c.relnamespace
JOIN pg_catalog.pg_class rc ON rc.oid = con.confrelid
JOIN pg_catalog.pg_namespace rn ON rn.oid = rc.relnamespace
WHERE con.contype = 'f'
  AND c.relname = '${pgTableName(table)}'
  AND ${pgSchemaPredicate(table)}
ORDER BY con.conname`;
    const out = await executeSql(connectionId, sql, database);
    return out.rows.map((row) => {
      const name = String(row[0] ?? "");
      const refSchema = String(row[3] ?? "");
      const refTable = String(row[2] ?? "");
      return {
        key: `fk-${name}`,
        name,
        columns: String(row[1] ?? ""),
        refTable:
          refSchema && refSchema !== "public" ? `${refSchema}.${refTable}` : refTable,
        refColumns: String(row[4] ?? ""),
        onDelete: PG_FK_ACTION[String(row[5] ?? "a")] ?? "NO ACTION",
        onUpdate: PG_FK_ACTION[String(row[6] ?? "a")] ?? "NO ACTION",
        originalName: name,
      };
    });
  }

  if (engineKey(engine) === "sqlite") {
    const out = await executeSql(
      connectionId,
      `PRAGMA foreign_key_list(${sqliteLiteral(table)})`,
      database,
    );
    const m = colMap(out.columns);
    const byId = new Map<string, DesignerForeignKey>();
    for (const row of out.rows) {
      const id = cell(row, m.id);
      const refTable = cell(row, m.table);
      const prev = byId.get(id);
      const from = cell(row, m.from);
      const to = cell(row, m.to);
      if (prev) {
        prev.columns = `${prev.columns}, ${from}`;
        prev.refColumns = `${prev.refColumns}, ${to}`;
      } else {
        byId.set(id, {
          key: `fk-${id}`,
          name: `fk_${refTable}_${id}`,
          columns: from,
          refTable,
          refColumns: to,
          onDelete: cell(row, m.on_delete) || "NO ACTION",
          onUpdate: cell(row, m.on_update) || "NO ACTION",
          originalName: `fk_${refTable}_${id}`,
        });
      }
    }
    return [...byId.values()];
  }

  if (engineKey(engine) !== "mysql") return [];
  const sql = `SELECT CONSTRAINT_NAME, COLUMN_NAME, REFERENCED_TABLE_NAME, REFERENCED_COLUMN_NAME
FROM information_schema.KEY_COLUMN_USAGE
WHERE TABLE_SCHEMA = '${database.replace(/'/g, "''")}'
  AND TABLE_NAME = '${table.replace(/'/g, "''")}'
  AND REFERENCED_TABLE_NAME IS NOT NULL
ORDER BY CONSTRAINT_NAME, ORDINAL_POSITION`;
  const out = await executeSql(connectionId, sql, database);
  const byName = new Map<string, DesignerForeignKey>();
  for (const row of out.rows) {
    const name = String(row[0] ?? "");
    const col = String(row[1] ?? "");
    const refTable = String(row[2] ?? "");
    const refCol = String(row[3] ?? "");
    const prev = byName.get(name);
    if (prev) {
      prev.columns = `${prev.columns}, ${col}`;
      prev.refColumns = `${prev.refColumns}, ${refCol}`;
    } else {
      byName.set(name, {
        key: `fk-${name}`,
        name,
        columns: col,
        refTable,
        refColumns: refCol,
        onDelete: "RESTRICT",
        onUpdate: "RESTRICT",
        originalName: name,
      });
    }
  }
  // fill ON DELETE/UPDATE
  const rulesSql = `SELECT CONSTRAINT_NAME, UPDATE_RULE, DELETE_RULE
FROM information_schema.REFERENTIAL_CONSTRAINTS
WHERE CONSTRAINT_SCHEMA = '${database.replace(/'/g, "''")}'
  AND TABLE_NAME = '${table.replace(/'/g, "''")}'`;
  try {
    const rules = await executeSql(connectionId, rulesSql, database);
    for (const row of rules.rows) {
      const name = String(row[0] ?? "");
      const fk = byName.get(name);
      if (fk) {
        fk.onUpdate = String(row[1] ?? "RESTRICT");
        fk.onDelete = String(row[2] ?? "RESTRICT");
      }
    }
  } catch {
    /* ignore */
  }
  return [...byName.values()];
}

export async function loadDesignerTriggers(args: {
  connectionId: string;
  engine: string;
  database: string;
  table: string;
}): Promise<DesignerTrigger[]> {
  const { connectionId, engine, database, table } = args;
  await openConnection(connectionId);

  if (isPostgres(engine)) {
    const sql = `SELECT t.tgname AS name,
       pg_catalog.pg_get_triggerdef(t.oid) AS definition
FROM pg_catalog.pg_trigger t
JOIN pg_catalog.pg_class c ON c.oid = t.tgrelid
JOIN pg_catalog.pg_namespace n ON n.oid = c.relnamespace
WHERE NOT t.tgisinternal
  AND c.relname = '${pgTableName(table)}'
  AND ${pgSchemaPredicate(table)}
ORDER BY t.tgname`;
    const out = await executeSql(connectionId, sql, database);
    return out.rows.map((row) => {
      const name = String(row[0] ?? "");
      const def = String(row[1] ?? "");
      const timing =
        def.match(/\b(BEFORE|AFTER|INSTEAD\s+OF)\b/i)?.[1]?.toUpperCase() ??
        "BEFORE";
      const event =
        def.match(/\b(INSERT|UPDATE|DELETE|TRUNCATE)\b/i)?.[1]?.toUpperCase() ??
        "INSERT";
      const exec = def.match(/\bEXECUTE\s+(?:FUNCTION|PROCEDURE)\s+[\s\S]+$/i)?.[0] ?? "";
      return {
        key: `tr-${name}`,
        name,
        timing,
        event,
        statement: exec,
        originalName: name,
      };
    });
  }

  if (engineKey(engine) === "sqlite") {
    const out = await executeSql(
      connectionId,
      `SELECT name, sql FROM sqlite_master
       WHERE type = 'trigger' AND tbl_name = ${sqliteLiteral(table)}
       ORDER BY name`,
      database,
    );
    return out.rows.map((row) => {
      const name = String(row[0] ?? "");
      const parsed = parseSqliteTrigger(String(row[1] ?? ""));
      return {
        key: `tr-${name}`,
        name,
        ...parsed,
        originalName: name,
      };
    });
  }

  if (engineKey(engine) !== "mysql") return [];
  const sql = `SELECT TRIGGER_NAME, ACTION_TIMING, EVENT_MANIPULATION, ACTION_STATEMENT
FROM information_schema.TRIGGERS
WHERE TRIGGER_SCHEMA = '${database.replace(/'/g, "''")}'
  AND EVENT_OBJECT_TABLE = '${table.replace(/'/g, "''")}'`;
  const out = await executeSql(connectionId, sql, database);
  return out.rows.map((row) => ({
    key: `tr-${row[0]}`,
    name: String(row[0] ?? ""),
    timing: String(row[1] ?? "BEFORE"),
    event: String(row[2] ?? "INSERT"),
    statement: String(row[3] ?? ""),
    originalName: String(row[0] ?? ""),
  }));
}

export async function loadDesignerChecks(args: {
  connectionId: string;
  engine: string;
  database: string;
  table: string;
}): Promise<DesignerCheck[]> {
  const { connectionId, engine, database, table } = args;
  await openConnection(connectionId);

  if (isPostgres(engine)) {
    const sql = `SELECT con.conname AS name,
       pg_catalog.pg_get_constraintdef(con.oid) AS definition
FROM pg_catalog.pg_constraint con
JOIN pg_catalog.pg_class c ON c.oid = con.conrelid
JOIN pg_catalog.pg_namespace n ON n.oid = c.relnamespace
WHERE con.contype = 'c'
  AND c.relname = '${pgTableName(table)}'
  AND ${pgSchemaPredicate(table)}
ORDER BY con.conname`;
    try {
      const out = await executeSql(connectionId, sql, database);
      return out.rows.map((row) => {
        const name = String(row[0] ?? "");
        let expression = String(row[1] ?? "").replace(/^CHECK\s*/i, "").trim();
        if (expression.startsWith("(") && expression.endsWith(")")) {
          expression = expression.slice(1, -1);
        }
        return { key: `ck-${name}`, name, expression, originalName: name };
      });
    } catch {
      return [];
    }
  }

  if (engineKey(engine) === "sqlite") {
    const out = await executeSql(
      connectionId,
      `SELECT sql FROM sqlite_master WHERE type = 'table' AND name = ${sqliteLiteral(table)}`,
      database,
    );
    return parseSqliteChecks(String(out.rows[0]?.[0] ?? ""));
  }

  if (engineKey(engine) !== "mysql") return [];
  const sql = `SELECT CONSTRAINT_NAME, CHECK_CLAUSE
FROM information_schema.CHECK_CONSTRAINTS cc
JOIN information_schema.TABLE_CONSTRAINTS tc
  ON cc.CONSTRAINT_SCHEMA = tc.CONSTRAINT_SCHEMA
 AND cc.CONSTRAINT_NAME = tc.CONSTRAINT_NAME
WHERE tc.TABLE_SCHEMA = '${database.replace(/'/g, "''")}'
  AND tc.TABLE_NAME = '${table.replace(/'/g, "''")}'
  AND tc.CONSTRAINT_TYPE = 'CHECK'`;
  try {
    const out = await executeSql(connectionId, sql, database);
    return out.rows.map((row) => ({
      key: `ck-${row[0]}`,
      name: String(row[0] ?? ""),
      expression: String(row[1] ?? ""),
      originalName: String(row[0] ?? ""),
    }));
  } catch {
    return [];
  }
}

