import { useRef, useState } from "react";
import type { ConnectionDto } from "../connections/types";
import {
  dumpTableSql,
  executeSql,
  fetchTablePage,
  listTables,
} from "../connections/sessionApi";
import { downloadTextFile } from "../import-export/csv";
import { useWorkspaceStore } from "../../stores/workspaceStore";

export type DbMenuTarget = {
  x: number;
  y: number;
  conn: ConnectionDto;
  database: string;
};

type Props = {
  target: DbMenuTarget;
  onClose: () => void;
  onRefresh: (connId: string) => Promise<void>;
  onCloseDatabase: (connId: string, database: string) => void;
  onMessage: (msg: string) => void;
};

function escapeIdent(name: string) {
  return name.replace(/`/g, "``");
}

export function DatabaseContextMenu({
  target,
  onClose,
  onRefresh,
  onCloseDatabase,
  onMessage,
}: Props) {
  const [dumpOpen, setDumpOpen] = useState(false);
  const [busy, setBusy] = useState(false);
  const sqlFileRef = useRef<HTMLInputElement>(null);
  const setCenterMode = useWorkspaceStore((s) => s.setCenterMode);
  const openConn = useWorkspaceStore((s) => s.openConnection);
  const selectDatabase = useWorkspaceStore((s) => s.selectDatabase);
  const selectObjectFolder = useWorkspaceStore((s) => s.selectObjectFolder);
  const setObjectListFilter = useWorkspaceStore((s) => s.setObjectListFilter);
  const openQuery = useWorkspaceStore((s) => s.openQuery);
  const setToolbarAction = useWorkspaceStore((s) => s.setToolbarAction);

  const { conn, database } = target;

  function ensureContext() {
    openConn(conn);
    selectDatabase(database);
  }

  async function run(action: () => Promise<void> | void) {
    try {
      setBusy(true);
      await action();
      onClose();
    } catch (err) {
      onMessage(err instanceof Error ? err.message : String(err));
    } finally {
      setBusy(false);
    }
  }

  async function dumpDatabase(includeData: boolean) {
    ensureContext();
    const tables = await listTables(conn.id, database);
    const parts: string[] = [
      `-- Dump of database \`${database}\``,
      `-- Generated by My Navicat`,
      `CREATE DATABASE IF NOT EXISTS \`${escapeIdent(database)}\`;`,
      `USE \`${escapeIdent(database)}\`;`,
      "",
    ];
    const baseTables = tables.filter((x) => x.kind !== "view");
    for (const t of baseTables) {
      const sql = await dumpTableSql({
        connectionId: conn.id,
        table: t.name,
        includeData,
        engine: String(conn.engine),
      });
      parts.push(sql, "");
    }
    downloadTextFile(
      `${database}${includeData ? "" : "-structure"}.sql`,
      parts.join("\n"),
      "application/sql",
    );
    onMessage(`已导出 ${baseTables.length} 张表`);
  }

  async function exportDataDictionary() {
    ensureContext();
    const tables = await listTables(conn.id, database);
    const lines: string[] = [
      `# 数据字典 · ${database}`,
      "",
      `连接：${conn.name}（${conn.engine}）`,
      `生成时间：${new Date().toLocaleString()}`,
      "",
    ];
    for (const t of tables) {
      lines.push(`## ${t.name}（${t.kind}）`);
      if (t.comment) lines.push(`备注：${t.comment}`);
      if (t.engine) lines.push(`引擎：${t.engine}`);
      if (t.collation) lines.push(`排序规则：${t.collation}`);
      if (t.tableRows != null) lines.push(`约 ${t.tableRows} 行`);
      lines.push("");
      lines.push("| 列名 | 类型 | 可空 |");
      lines.push("| --- | --- | --- |");
      try {
        const page = await fetchTablePage({
          connectionId: conn.id,
          table: t.name,
          page: 1,
          pageSize: 1,
        });
        for (const col of page.columns) {
          lines.push(
            `| ${col.name} | ${col.dataType} | ${col.nullable ? "YES" : "NO"} |`,
          );
        }
      } catch {
        lines.push("| （无法读取列信息） | | |");
      }
      lines.push("");
    }
    downloadTextFile(
      `${database}-data-dictionary.md`,
      lines.join("\n"),
      "text/markdown",
    );
    onMessage(`已导出数据字典（${tables.length} 个对象）`);
  }

  async function exportReverseModel() {
    ensureContext();
    const tables = await listTables(conn.id, database);
    const baseTables = tables.filter((x) => x.kind !== "view");
    const lines: string[] = [
      `# 逆向模型 · ${database}`,
      "",
      "```mermaid",
      "erDiagram",
    ];
    for (const t of baseTables) {
      const safe = t.name.replace(/[^A-Za-z0-9_]/g, "_");
      lines.push(`  ${safe} {`);
      try {
        const page = await fetchTablePage({
          connectionId: conn.id,
          table: t.name,
          page: 1,
          pageSize: 1,
        });
        for (const col of page.columns.slice(0, 12)) {
          const typ = col.dataType.replace(/\s+/g, "_").replace(/[^A-Za-z0-9_]/g, "");
          lines.push(`    ${typ || "string"} ${col.name}`);
        }
      } catch {
        lines.push("    string id");
      }
      lines.push("  }");
    }
    lines.push("```", "");
    downloadTextFile(
      `${database}-model.md`,
      lines.join("\n"),
      "text/markdown",
    );
    setToolbarAction("model", "model");
    onMessage(`已生成逆向模型（${baseTables.length} 张表）`);
  }

  return (
    <div
      className="dg-context-menu tree-context-menu"
      style={{ left: target.x, top: target.y }}
      onClick={(e) => e.stopPropagation()}
      onContextMenu={(e) => e.preventDefault()}
    >
      <button
        type="button"
        disabled={busy}
        onClick={() => {
          onCloseDatabase(conn.id, database);
          onClose();
        }}
      >
        关闭数据库
        <span className="menu-shortcut">⇧⌘.</span>
      </button>
      <div className="dg-menu-sep" />
      <button
        type="button"
        disabled={busy}
        onClick={() =>
          void run(async () => {
            const charset =
              window.prompt("字符集（例如 utf8mb4）", "utf8mb4")?.trim() || "";
            if (!charset) return;
            const collate =
              window
                .prompt(
                  "排序规则（例如 utf8mb4_general_ci）",
                  "utf8mb4_general_ci",
                )
                ?.trim() || "";
            ensureContext();
            let sql = `ALTER DATABASE \`${escapeIdent(database)}\` CHARACTER SET ${charset}`;
            if (collate) sql += ` COLLATE ${collate}`;
            await executeSql(conn.id, sql);
            onMessage("数据库属性已更新");
            await onRefresh(conn.id);
          })
        }
      >
        编辑数据库…
      </button>
      <button
        type="button"
        disabled={busy}
        onClick={() =>
          void run(async () => {
            const name = window.prompt("新数据库名称")?.trim();
            if (!name) return;
            if (!/^[A-Za-z0-9_]+$/.test(name)) {
              throw new Error("数据库名仅允许字母、数字、下划线");
            }
            ensureContext();
            await executeSql(conn.id, `CREATE DATABASE \`${name}\``);
            onMessage(`已创建数据库 ${name}`);
            await onRefresh(conn.id);
          })
        }
      >
        新建数据库…
      </button>
      <button
        type="button"
        disabled={busy}
        onClick={() =>
          void run(async () => {
            if (
              !window.confirm(
                `确定删除数据库「${database}」？此操作不可恢复。`,
              )
            ) {
              return;
            }
            ensureContext();
            // Avoid "cannot drop database while in use" on MySQL.
            if (String(conn.engine) === "mysql") {
              try {
                await executeSql(conn.id, "USE `information_schema`");
              } catch {
                // ignore
              }
            }
            await executeSql(
              conn.id,
              `DROP DATABASE \`${escapeIdent(database)}\``,
            );
            onCloseDatabase(conn.id, database);
            onMessage(`已删除数据库 ${database}`);
            await onRefresh(conn.id);
          })
        }
      >
        删除数据库
      </button>
      <div className="dg-menu-sep" />
      <button
        type="button"
        disabled={busy}
        onClick={() => {
          ensureContext();
          openQuery({ connection: conn, database });
          onClose();
        }}
      >
        新建查询
        <span className="menu-shortcut">⌘Y</span>
      </button>
      <div className="dg-menu-sep" />
      <button
        type="button"
        disabled={busy}
        onClick={() => {
          ensureContext();
          setCenterMode("console");
          onClose();
        }}
      >
        命令列界面
      </button>
      <button
        type="button"
        disabled={busy}
        onClick={() => sqlFileRef.current?.click()}
      >
        运行 SQL 文件…
      </button>
      <input
        ref={sqlFileRef}
        type="file"
        accept=".sql,text/plain"
        hidden
        onChange={(e) => {
          const file = e.target.files?.[0];
          e.target.value = "";
          if (!file) return;
          void run(async () => {
            ensureContext();
            const text = await file.text();
            if (String(conn.engine) === "mysql") {
              await executeSql(
                conn.id,
                `USE \`${escapeIdent(database)}\``,
              );
            }
            await executeSql(conn.id, text);
            onMessage(`已执行 ${file.name}`);
            await onRefresh(conn.id);
          });
        }}
      />
      <div
        className={`dg-menu-item has-sub ${dumpOpen ? "is-open" : ""}`}
        onMouseEnter={() => setDumpOpen(true)}
        onMouseLeave={() => setDumpOpen(false)}
      >
        <button type="button" className="dg-menu-trigger" disabled={busy}>
          转储 SQL 文件
          <span className="dg-menu-arrow">›</span>
        </button>
        {dumpOpen && (
          <div className="dg-submenu">
            <button
              type="button"
              onClick={() => void run(() => dumpDatabase(true))}
            >
              结构和数据…
            </button>
            <button
              type="button"
              onClick={() => void run(() => dumpDatabase(false))}
            >
              仅结构…
            </button>
          </div>
        )}
      </div>
      <button
        type="button"
        disabled={busy}
        onClick={() => void run(() => exportDataDictionary())}
      >
        数据字典…
      </button>
      <button
        type="button"
        disabled={busy}
        onClick={() => void run(() => exportReverseModel())}
      >
        逆向数据库到模型…
      </button>
      <button
        type="button"
        disabled={busy}
        onClick={() => {
          ensureContext();
          selectObjectFolder(database, "tables");
          const q =
            window.prompt("在数据库中查找（对象名称）", "")?.trim() ?? "";
          setObjectListFilter(q, true);
          onClose();
        }}
      >
        在数据库中查找…
      </button>
      <div className="dg-menu-sep" />
      <button
        type="button"
        disabled={busy}
        onClick={() =>
          void run(async () => {
            const text = [
              `连接：${conn.name}`,
              `引擎：${conn.engine}`,
              `主机：${conn.host}:${conn.port ?? ""}`,
              `数据库：${database}`,
            ].join("\n");
            await navigator.clipboard.writeText(text);
            onMessage("已复制共享信息到剪贴板");
          })
        }
      >
        共享…
      </button>
      <div className="dg-menu-sep" />
      <button
        type="button"
        disabled={busy}
        onClick={() =>
          void run(async () => {
            await onRefresh(conn.id);
            onMessage("已刷新");
          })
        }
      >
        刷新
        <span className="menu-shortcut">⌘R</span>
      </button>
    </div>
  );
}
